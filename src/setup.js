// setup.html: fully client-side. Verifies the .kdbx opens, then derives the gate token and
// produces data/config.php. No network access (the page also has CSP connect-src 'none').
import { DEFAULT_PARAMS, deriveAuthToken, buildVerifier, randomSalt } from './kdf.js';
import { Vault, isInvalidKeyError } from './vault.js';
import { hasKdbxSignature } from './bytes.js';
import { byId, show, setStatus, downloadBlob, errorMessage } from './dom.js';

const MAX_VAULT_BYTES = 20 * 1024 * 1024;

/** Renders data/config.php for a verifier (keys as in docs/SPEC.md). */
export function renderConfig(verifier, date = new Date()) {
  if (!/^[A-Za-z0-9$=,+/]+$/.test(verifier)) throw new Error('unexpected characters in verifier');
  return `<?php
// kdbx-gate configuration, generated by setup.html on ${date.toISOString().slice(0, 10)}.
// Upload this file as data/config.php. Re-run setup.html after changing the master password.
return [
    'verifier'        => '${verifier}',
    'vault_file'      => __DIR__ . '/vault.kdbx',  // may point outside the webroot
    'state_dir'       => __DIR__,                  // lockout.json + backups/ live here
    'free_attempts'   => 3,                        // failures allowed before the delay starts
    'delay_seconds'   => 60,                       // minimum spacing of attempts while locked
    'max_vault_bytes' => 20 * 1024 * 1024,
    'keep_backups'    => 10,
];
`;
}

function describeKdf(kdf) {
  if (kdf.name.startsWith('AES')) return `${kdf.name}, ${kdf.rounds.toLocaleString()} rounds`;
  return `${kdf.name}, ${kdf.memoryKiB / 1024} MiB, ${kdf.iterations} iterations, parallelism ${kdf.parallelism}`;
}

function readInt(input, fallback) {
  const n = Number.parseInt(input.value, 10);
  return Number.isInteger(n) ? n : fallback;
}

function init() {
  const el = {
    form: byId('setup-form'),
    kdbx: byId('setup-kdbx'),
    password: byId('setup-password'),
    keyToggle: byId('setup-keyfile-toggle'),
    keyRow: byId('setup-keyfile-row'),
    keyFile: byId('setup-keyfile'),
    m: byId('setup-m'),
    t: byId('setup-t'),
    p: byId('setup-p'),
    go: byId('setup-go'),
    status: byId('setup-status'),
    result: byId('setup-result'),
    info: byId('setup-info'),
    config: byId('setup-config'),
    download: byId('setup-download'),
    copy: byId('setup-copy'),
  };
  const status = (type, text) => setStatus(el.status, type, text);

  el.keyToggle.addEventListener('click', () => {
    const open = el.keyRow.hidden;
    show(el.keyRow, open);
    el.keyToggle.setAttribute('aria-expanded', String(open));
    if (!open) el.keyFile.value = '';
  });

  el.form.addEventListener('submit', async (event) => {
    event.preventDefault();
    show(el.result, false);
    el.config.value = '';
    const file = el.kdbx.files && el.kdbx.files[0];
    const password = el.password.value;
    if (!file) return status('error', 'Choose your .kdbx file.');
    if (!password) return status('error', 'Enter the master password.');
    const params = {
      m: readInt(el.m, DEFAULT_PARAMS.m),
      t: readInt(el.t, DEFAULT_PARAMS.t),
      p: readInt(el.p, DEFAULT_PARAMS.p),
    };
    el.go.disabled = true;
    try {
      status('info', 'Opening the database…');
      const bytes = await file.arrayBuffer();
      if (!hasKdbxSignature(bytes)) return status('error', 'This is not a KeePass 2 (.kdbx) file.');
      const keyFileInput = !el.keyRow.hidden && el.keyFile.files && el.keyFile.files[0];
      const keyFile = keyFileInput ? await keyFileInput.arrayBuffer() : null;

      let vault;
      try {
        vault = await Vault.open(bytes, password, keyFile);
      } catch (err) {
        if (isInvalidKeyError(err)) {
          return status('error', `Wrong password${keyFile ? ' or key file' : ' (or the database needs a key file)'}: the database could not be decrypted.`);
        }
        return status('error', `The database could not be opened: ${errorMessage(err)}`);
      }
      const info = vault.info;
      const count = vault.listEntries().length;
      vault.close();

      status('info', `Deriving the server check value (Argon2id, ${Math.round(params.m / 1024)} MiB)…`);
      const kdfParams = { ...params, salt: randomSalt() };
      const token = await deriveAuthToken(password, kdfParams);
      const verifier = await buildVerifier(token, kdfParams);
      el.config.value = renderConfig(verifier);
      el.password.value = '';

      const notes = [
        `Database OK: KDBX ${info.version}, ${info.cipher}, ${describeKdf(info.kdf)}, ${count} entr${count === 1 ? 'y' : 'ies'}.`,
      ];
      if (keyFile) notes.push('Your key file is not part of config.php: keep it on each device you unlock from.');
      if (bytes.byteLength > MAX_VAULT_BYTES) notes.push('The database is larger than 20 MiB: raise max_vault_bytes in config.php.');
      el.info.textContent = notes.join(' ');
      show(el.result, true);
      status('ok', 'Done. Download config.php and follow the steps below.');
      el.result.scrollIntoView({ block: 'start' });
    } catch (err) {
      status('error', errorMessage(err));
    } finally {
      el.go.disabled = false;
    }
  });

  el.download.addEventListener('click', () => {
    if (el.config.value) downloadBlob(el.config.value, 'config.php', 'text/plain;charset=utf-8');
  });

  el.copy.addEventListener('click', async () => {
    if (!el.config.value) return;
    try {
      await navigator.clipboard.writeText(el.config.value);
      status('ok', 'config.php copied to the clipboard.');
    } catch {
      el.config.select();
      status('info', 'Select the text and copy it manually.');
    }
  });
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
}
